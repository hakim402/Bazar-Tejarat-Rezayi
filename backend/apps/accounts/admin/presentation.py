def text(label):
    if get_language() == "fa-af" and label in DARI:
        return DARI[label]
    return gettext(label)


label = lazy(text, str)


def action_label(value):
    """Readable text for a stored action slug, translated when a copy exists."""
    readable = str(value or "").replace("_", " ").strip().capitalize()
    return label(readable) if readable else "—"

