"""Role groups; deletion disabled to preserve grant history."""
from django.contrib.auth.admin import GroupAdmin
from django.contrib.auth.models import Group
from unfold.admin import ModelAdmin
from unfold.decorators import display

from .display import record_identity
from .presentation import label
from .site import owner_site


class RoleAdmin(GroupAdmin, ModelAdmin):
    actions = []
    list_display = ["role_name", "member_count", "permission_count"]
    search_fields = ["name"]
    ordering = ["name"]

    def has_delete_permission(self, request, obj=None):
        return False

    def get_fieldsets(self, request, obj=None):
        return [
            (label("Role configuration"), {
                "fields": ["name"],
                "description": label("A role groups the permissions a staff account may use."),
            }),
            (label("Granted permissions"), {
                "fields": ["permissions"],
                "description": label("Permission metadata itself is generated by Django and listed on the permissions page."),
            }),
        ]

    @display(description=label("Role"), ordering="name")
    def role_name(self, obj):
        return record_identity(obj.name, label("Role configuration"), glyph="groups")

    @display(description=label("Staff accounts"))
    def member_count(self, obj):
        return obj.user_set.count()

    @display(description=label("Permissions"))
    def permission_count(self, obj):
        return obj.permissions.count()


owner_site.register(Group, RoleAdmin)
